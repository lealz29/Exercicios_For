public class ExercicioForQuadrado_2 {
    public static void main(String[] args) {
        
        // Iniciamos em 15 e vamos até 100
        for (int i = 15; i <= 100; i++) {
            // Calculamos o quadrado multiplicando o número por ele mesmo
            int quadrado = i * i;
            
            // Exibimos a mensagem formatada conforme o exemplo
            System.out.println("O quadrado de " + i + " é " + quadrado);
        }
        
    }
}
 

